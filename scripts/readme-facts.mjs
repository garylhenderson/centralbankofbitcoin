#!/usr/bin/env node
// THE README'S FACTS, GENERATED FROM THE FILES THAT OWN THEM (Gary 2026-10-10:
// "add in a readme so it's complete and makes sense, and make sure it stays up
// to date").
//
// Every fact in README.md that can drift (program ids, the Core build we test
// against, the release commit, the launch values, the assertion floors, the
// audit verdicts, the road to launch) lives between two markers and is written
// by this script from its one source. Nothing in that block is typed by hand.
// scripts/run-tests.sh runs `--check`, so a run fails when README.md no longer
// says what the sources say. A README that is checked is one that stays true.
//
// Usage: node scripts/readme-facts.mjs --write   regenerate the block in place
//        node scripts/readme-facts.mjs --check   exit 1 if it is stale (prints the first difference)
import fs from 'fs'

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '')
const read = f => fs.readFileSync(`${ROOT}/${f}`, 'utf8')
const BEGIN = '<!-- readme-facts:begin (generated by scripts/readme-facts.mjs --write; edits here are overwritten) -->'
const END = '<!-- readme-facts:end -->'
const need = (v, what) => { if (v === undefined || v === null || v === '') throw new Error(`readme-facts: could not read ${what}`); return v }

function programs() {
  const src = read('bank/layout.mjs')
  const block = need((src.match(/export const PROGRAM_IDS = \{([\s\S]*?)\n\}/) || [])[1], 'PROGRAM_IDS in bank/layout.mjs')
  const ids = Object.fromEntries([...block.matchAll(/^\s*(\w+): '([1-9A-HJ-NP-Za-km-z]{32,44})'/gm)].map(m => [m[1], m[2]]))
  const rows = [
    ['seal', 'SEAL', 'cbob-vaults', 'holds each vault\'s reserves; nothing leaves until the owner opens it'],
    ['mint', 'MINT', 'cbob-vault-mint', 'charter claims and sale rounds, the on-chain level draw, the revenue split and the community pool'],
    ['burn', 'BURN', 'cbob-vault-burn', 'opening a vault: pays out its reserves to the owner and burns it'],
    ['gov', 'GOV', 'cbob-vault-gov', 'one vault, one vote: rounds, prices, and restarting anything the guardian stopped'],
    ['sweep', 'SWEEP', 'cbob-vault-sweep', 'stateless helper the open page calls to empty a vault\'s wallet'],
  ]
  for (const [k] of rows) need(ids[k], `program id "${k}"`)
  if (Object.keys(ids).length !== rows.length) throw new Error('readme-facts: PROGRAM_IDS has a program this table does not describe')
  return ['| program | address | source | what it does |', '|---|---|---|---|',
    ...rows.map(([k, n, dir, what]) => {
      if (!fs.existsSync(`${ROOT}/programs/${dir}`)) throw new Error(`readme-facts: programs/${dir} is missing`)
      return `| ${n} | \`${ids[k]}\` | [\`programs/${dir}\`](programs/${dir}) | ${what} |`
    })].join('\n')
}

function launchValues() {
  const j = JSON.parse(read('launch/mainnet-init.json'))
  const v = k => need(j[k], `launch/mainnet-init.json ${k}`)
  const val = k => { const x = v(k); return x.value === null || x.value === undefined ? 'not set yet' : Array.isArray(x.value) ? x.value.map(a => `\`${a}\``).join(', ') : `\`${x.value}\`` }
  return ['| launch value | set to | status |', '|---|---|---|',
    ...[['init_authority', 'signs the one-time setup (the guardian wallet)'], ['guardian', 'may only stop sales or the swap bot, or cancel a new swap-bot key; only a vote restarts'],
      ['bank_treasury', 'receives the Bank\'s 15% (the CBOBTC Squads multisig); signs nothing'], ['payment_mint', 'sale rounds are priced in'],
      ['reserve_mints', 'the three tokens a vault holds'], ['vault_collection', 'the Core collection every vault belongs to']]
      .map(([k, what]) => `| \`${k}\`: ${what} | ${val(k)} | ${v(k).status} |`)].join('\n')
}

function floors() {
  const rt = read('scripts/run-tests.sh'), sim = read('sim/run-sim.sh'), e2e = read('web/test/e2e-localnet.sh'), sw = read('sim/swap-fork.sh')
  const f = (src, name, file) => need((src.match(new RegExp(`^${name}=(\\d+)`, 'm')) || [])[1], `${name} in ${file}`)
  const rows = [
    ['on-chain suite (real mainnet Core, real SPL tokens)', f(rt, 'MIN_ASSERTIONS', 'run-tests.sh'), 'scripts/run-tests.sh'],
    ['alarm detectors, each proven to fire and to stay quiet', f(rt, 'DET_FLOOR', 'run-tests.sh'), 'bank/selftest.mjs'],
    ['holder pages, ceremony and RPC relay (offline)', f(rt, 'WEB_FLOOR', 'run-tests.sh'), 'web/test/run-all.mjs'],
    ['holder pages end to end on a local chain', f(e2e, 'E2E_FLOOR', 'e2e-localnet.sh'), 'web/test/e2e-localnet.sh'],
    ['Test Vault simulation: one vault\'s whole life', f(sim, 'SIM_FLOOR', 'run-sim.sh'), 'sim/run-sim.sh'],
    ['launch values judge', f(rt, 'LAUNCH_FLOOR', 'run-tests.sh'), 'scripts/check-launch-params.mjs'],
    ['payout arithmetic', f(rt, 'ALLOC_FLOOR', 'run-tests.sh'), 'bank/accrual.mjs'],
    ['live mainnet facts (Core build, token programs, Proof of Burn set)', f(rt, 'MAINNET_FLOOR', 'run-tests.sh'), 'scripts/probe-mainnet-facts.mjs'],
    ['swap fork against real pools', f(sw, 'SWAP_FLOOR', 'swap-fork.sh'), 'sim/swap-fork.sh'],
  ]
  return ['| test set | assertions (must equal, not just reach) | run by |', '|---|---|---|',
    ...rows.map(([what, n, by]) => `| ${what} | ${n} | \`${by}\` |`)].join('\n')
}

function core() {
  const pin = need((read('scripts/run-tests.sh').match(/^CORE_SHA256_EXPECTED=([0-9a-f]{64})$/m) || [])[1], 'CORE_SHA256_EXPECTED')
  const rel = need((read('web/src/config.js').match(/^export const RELEASE_COMMIT = '([0-9a-f]{40})'/m) || [])[1], 'RELEASE_COMMIT')
  return [`- **Program source released for launch:** commit \`${rel}\` (\`${rel.slice(0, 7)}\`). \`web/src/config.js\` RELEASE_COMMIT; the build refuses any other.`,
    `- **Metaplex Core build every test runs against:** sha256 \`${pin}\` (the bytes after the 45-byte ProgramData header, as \`solana program dump\` writes them). \`scripts/run-tests.sh\` CORE_SHA256_EXPECTED.`].join('\n')
}

function audits() {
  const rounds = fs.readdirSync(`${ROOT}/audits`).map(d => (d.match(/^round(\d+)$/) || [])[1]).filter(Boolean).map(Number)
    .filter(n => fs.existsSync(`${ROOT}/audits/round${n}/VERDICT-programs.md`)).sort((a, b) => a - b)
  need(rounds.length || null, 'any audits/roundN/VERDICT-programs.md')
  const verdict = (n, p) => {
    const f = `${ROOT}/audits/round${n}/VERDICT-${p}.md`
    if (!fs.existsSync(f)) return 'not run'
    const h = fs.readFileSync(f, 'utf8').split('\n')[0]
    return need((h.match(/pass: ([A-Z-]+(?: [A-Z-]+)*)/) || [])[1], `the verdict line of ${f}`)
  }
  // a round whose repairs were validated has a VALIDATION.md; one still owed says REQUIRES CHANGES in its verdict
  const changes = n => {
    if (fs.existsSync(`${ROOT}/audits/round${n}/VALIDATION.md`)) return `yes, [validated](audits/round${n}/VALIDATION.md)`
    const owed = ['programs', 'offchain'].some(p => { const f = `${ROOT}/audits/round${n}/VERDICT-${p}.md`; return fs.existsSync(f) && /^REQUIRES CHANGES: \S/m.test(fs.readFileSync(f, 'utf8')) })
    return owed ? 'yes, repairs not yet validated' : 'none'
  }
  const last = rounds.slice(-6)
  const all = fs.readdirSync(`${ROOT}/audits`).map(d => (d.match(/^round(\d+)$/) || [])[1]).filter(Boolean).map(Number).sort((a, b) => a - b)
  return [`${all.length} audit rounds are in [\`audits/\`](audits) (rounds ${all[0]} to ${all.at(-1)}; the log of every one is [\`audits/FREEZE.md\`](audits/FREEZE.md)). The launch gate needs a round whose findings require NO changes. The latest ${last.length}:`, '',
    '| round | five programs | off-chain code | needed changes |', '|---|---|---|---|',
    ...last.map(n => `| [${n}](audits/round${n}) | ${verdict(n, 'programs')} | ${verdict(n, 'offchain')} | ${changes(n)} |`)].join('\n')
}

function road() {
  const spec = read('SPEC.md')
  const start = spec.indexOf('### The road from here to Bitcoin (v6), in order')
  if (start < 0) throw new Error('readme-facts: SPEC.md has no road section')
  const labels = ['Design approved', 'Programs built', 'Test suite and off-chain pipeline', 'Independent red-team passes', 'Test Vault simulation',
    'Launch values and holder pages', 'Audit rounds (the launch gate)', 'Mainnet dress rehearsal', 'Deploy the five programs', 'Create the collection and initialize (the guardian wallet signs)',
    'Lock: remove every upgrade authority, forever']
  const rows = [...spec.slice(start, start + 20000).matchAll(/^\| (\d+) \| .*\| ([^|]*) \|$/gm)].slice(0, labels.length)
  if (rows.length !== labels.length || rows.some((r, i) => Number(r[1]) !== i + 1)) throw new Error('readme-facts: SPEC road table is not steps 1..11')
  const short = s => {
    const t = s.replace(/\*\*|`/g, '').replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').trim()
    const cut = t.search(/:|\. /)
    const one = (cut > 0 ? t.slice(0, cut) : t).trim()
    return one.length > 110 ? one.slice(0, 107).replace(/\s+\S*$/, '') + '...' : one
  }
  return ['| step | | state (from SPEC.md) |', '|---|---|---|', ...rows.map((r, i) => `| ${i + 1} | ${labels[i]} | ${short(r[2])} |`)].join('\n')
}

export function generate() {
  return [BEGIN, '', '### The five programs', '', programs(), '', '### What launch writes once, and who holds what', '', launchValues(), '',
    '### What the tests run against', '', core(), '', '### Tests', '', floors(), '', '### Audits', '', audits(), '',
    '### The road to launch', '', road(), '', END].join('\n')
}

const args = process.argv.slice(2)
if (args.includes('--write') || args.includes('--check')) {
  const readme = read('README.md')
  const a = readme.indexOf(BEGIN), b = readme.indexOf(END)
  if (a < 0 || b < a) { console.error('README.md has no generated facts block'); process.exit(1) }
  const want = generate()
  const have = readme.slice(a, b + END.length)
  if (args.includes('--write')) {
    if (have !== want) fs.writeFileSync(`${ROOT}/README.md`, readme.slice(0, a) + want + readme.slice(b + END.length))
    console.log(have === want ? 'README facts already current' : 'README facts rewritten')
  } else if (have !== want) {
    const h = have.split('\n'), w = want.split('\n'), i = w.findIndex((l, k) => l !== h[k])
    console.error(`README.md is STALE at facts line ${i + 1}:\n  README: ${h[i] ?? '(missing)'}\n  source: ${w[i] ?? '(missing)'}\nRun: node scripts/readme-facts.mjs --write`)
    process.exit(1)
  } else console.log('README facts current: every generated line equals its source')
}
