import { harness } from './ref.mjs'
import { position, reserveValues, basketHistory, validObservation } from '../src/lib/position.mjs'
const H=harness('position')
const vault=(asset,owner='me',extra={})=>({asset,owner,status:'earning',level:2,reserves:{cbBTC:'123',GARY:'200',GIRAFFISH:'300'},value_usd:20,owed_sats:'5',...extra})
const d={vaults:[vault('a'),vault('b'),vault('c','other'),vault('d','me',{status:'opened'})]}
const p=position(d,'me')
H.eq('only current owned live vaults count',p.vaults.map(v=>v.asset),['a','b'])
H.eq('live reserve value sums without wallet balance or pending payouts',p.value,40)
H.eq('pending sats sum separately',p.owed,'10')
H.eq('token totals use exact integer arithmetic',p.held,{cbBTC:'246',GARY:'400',GIRAFFISH:'600'})
H.eq('earning status is counted',p.earning,2)
H.eq('collection cabinet counts each actual level',p.levels.map(l=>l.count),[0,2,0,0,0])
H.eq('no owner never implies everybody',position(d,'').vaults,[])
H.eq('no live vaults is a real zero',position({vaults:[]},'me').value,0)
H.eq('missing vault valuation makes aggregate unavailable',position({vaults:[vault('a'),vault('b','me',{value_usd:null})]},'me').value,null)
H.eq('missing token balance cannot understate aggregate',position({vaults:[vault('a'),vault('b','me',{reserves:{}})]},'me').held.cbBTC,null)
H.eq('missing owed amount remains unavailable',position({vaults:[vault('a','me',{owed_sats:null})]},'me').owed,null)
H.eq('zero balance needs no price',reserveValues({cbBTC:'0'},{cbBTC:null})[0].value,0)
H.eq('nonzero balance with absent price is unavailable',reserveValues({cbBTC:'1'},{})[0].value,null)
H.eq('missing balance is unavailable even with price',reserveValues({}, {cbBTC:100})[0].value,null)
H.eq('token decimals are applied',reserveValues({cbBTC:'100000000',GARY:'2000000000',GIRAFFISH:'3000000'},{cbBTC:100,GARY:2,GIRAFFISH:3}).map(r=>r.value),[100,4,9])
const history={daily:{a:[[1,10],[2,20],[3,null],[4,40]],b:[[2,30],[3,40],[4,50]]}}
H.eq('basket requires common priced observations, excluding future',basketHistory([vault('a'),vault('b')],history,3*86400),[[2*86400,50]])
H.eq('empty basket never fabricates a history',basketHistory([],history,1e9),[])
H.eq('missing one vault history makes basket unavailable',basketHistory([vault('a'),vault('z')],history,1e9),[])
H.eq('zero price is unavailable for a nonzero token balance',reserveValues({cbBTC:'1'},{cbBTC:0})[0].value,null)
H.eq('NaN price is unavailable',reserveValues({cbBTC:'1'},{cbBTC:NaN})[0].value,null)
H.eq('newer same-day history cannot replace an older current snapshot',basketHistory([vault('a')],{generated_at:2*86400+100,daily:{a:[[1,10],[2,30]]}},2*86400+50),[[86400,10]])
H.eq('matching history permits the current day',basketHistory([vault('a')],{generated_at:2*86400+50,daily:{a:[[1,10],[2,30]]}},2*86400+50),[[86400,10],[2*86400,30]])
H.eq('legacy history omits uncertified same-day points',basketHistory([vault('a')],{daily:{a:[[1,10],[2,30]]}},2*86400+50),[[86400,10]])
H.eq('duplicate history days use the last observation',basketHistory([vault('a')],{daily:{a:[[1,10],[1,20]]}},3*86400),[[86400,20]])
H.t('missing observation time is invalid',!validObservation({}))
H.t('future observation is invalid',!validObservation({generated_at:1000},100))
H.t('recorded timestamp is valid',validObservation({generated_at:100},101))
export default H.done()
